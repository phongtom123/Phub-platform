// Browser fixtures only; no customer, inventory, order or payment writes.
const assert = require("node:assert/strict");
const os = require("node:os"), path = require("node:path");
const { chromium } = require(process.env.PHUB_PLAYWRIGHT_MODULE || "playwright");
const base = process.env.PHUB_USER_TEST_URL || "http://localhost:3001";
const product = { id: "P", sku: "CPU-TEST", name: "CPU kiểm thử", price: "2000000.00", currency: "VND", category: { id: "COMP", name: "Linh kiện" }, subcategory: { id: "CPU", name: "Vi xử lý" }, brand: "Intel", description: null, unit: "Cái", warranty_months: 12, images: [], specifications: [], specifications_text: null };
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PHUB_CHROMIUM_PATH || undefined, args: ["--disable-features=LocalNetworkAccessChecks"] });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const searches = [], errors = [], writes = [];
    let mode = "ready";
    page.on("pageerror", error => errors.push(error.message));
    await page.route("**/api/**", async route => {
      const request = route.request(), url = new URL(request.url()), endpoint = url.pathname;
      if (request.method() !== "GET") writes.push(endpoint);
      const ok = json => route.fulfill({ json });
      if (endpoint.endsWith("/auth/me") || endpoint.endsWith("/customer/me")) return route.fulfill({ status: 401, json: { error: { message: "Guest" } } });
      if (endpoint.endsWith("/categories")) return ok({ items: [{ id: "COMP", name: "Linh kiện", children: [{ id: "CPU", name: "Vi xử lý" }, { id: "GPU", name: "Card đồ họa" }] }] });
      if (endpoint.endsWith("/brands")) return ok({ items: [{ name: "Intel" }, { name: "AMD" }] });
      if (endpoint.endsWith("/facets")) return ok({ specs: [], brands: [{ value: "Intel", label: "Intel", count: 40 }, { value: "AMD", label: "AMD", count: 40 }], total: 40 });
      if (endpoint === "/api/catalog/products") {
        searches.push(url.searchParams);
        if (mode === "error") return route.fulfill({ status: 503, json: { error: { message: "Không tải được tìm kiếm thử nghiệm." } } });
        const empty = mode === "empty";
        return ok({ items: empty ? [] : [product], pagination: { page: Number(url.searchParams.get("page") || 1), page_size: Number(url.searchParams.get("page_size") || 20), total: empty ? 0 : 40, total_pages: empty ? 0 : Math.ceil(40 / Number(url.searchParams.get("page_size") || 20)) } });
      }
      if (endpoint.endsWith("/availability")) return ok({ id: "P", sku: product.sku, quantity: Number(url.searchParams.get("quantity") || 1), available: true });
      if (endpoint.startsWith("/api/catalog/")) return ok({ items: [] });
      throw new Error(`Unexpected API: ${endpoint}`);
    });
    const header = page.getByRole("banner");
    const filter = page.getByRole("form", { name: "Bộ lọc tìm kiếm", exact: true });
    const input = header.getByRole("searchbox", { name: "Tìm kiếm sản phẩm", exact: true });
    async function openSearch() { await input.waitFor(); await input.focus(); }
    async function openFilters() { await header.getByRole("button", { name: /^Bộ lọc/ }).click(); await filter.waitFor(); }
    await page.goto(base + "/main/profile");
    await input.waitFor();
    assert.equal(await header.getByRole("button", { name: "Mở tìm kiếm", exact: true }).count(), 0, "Search stays visible without a toggle");
    await header.getByRole("button", { name: "Tìm kiếm", exact: true }).getByText("Tìm kiếm", { exact: true }).waitFor();
    await header.getByRole("button", { name: "Mở danh mục", exact: true }).click();
    const menu = header.getByRole("navigation", { name: "Danh mục sản phẩm", exact: true });
    await menu.getByRole("link", { name: "Linh kiện", exact: true }).hover();
    await menu.getByRole("link", { name: "Vi xử lý", exact: true }).click();
    await page.waitForURL(url => url.searchParams.get("subcategory_id") === "CPU");
    assert.equal(await menu.count(), 0);
    await page.goto(base + "/main/profile");
    await openSearch(); await input.fill("cpu"); await openFilters();
    await filter.getByRole("combobox", { name: "Danh mục", exact: true }).selectOption("COMP");
    await filter.getByRole("combobox", { name: "Loại sản phẩm", exact: true }).selectOption("CPU");
    await filter.getByRole("combobox", { name: "Thương hiệu", exact: true }).selectOption("Intel");
    await filter.getByLabel("Giá từ", { exact: true }).fill("3000000");
    await filter.getByLabel("Giá đến", { exact: true }).fill("1000000");
    await filter.getByRole("alert").getByText("Giá từ không được lớn hơn giá đến.", { exact: true }).waitFor();
    assert.ok(await filter.getByRole("button", { name: "Xem kết quả", exact: true }).isDisabled());
    await filter.getByLabel("Giá từ", { exact: true }).fill("1000000");
    await filter.getByLabel("Giá đến", { exact: true }).fill("5000000");
    await filter.getByRole("combobox", { name: "Tình trạng hàng", exact: true }).selectOption("in-stock");
    await filter.getByRole("combobox", { name: "Sắp xếp", exact: true }).selectOption("price-asc");
    await page.screenshot({ path: path.join(os.tmpdir(), "phub-search-filters-desktop.png"), fullPage: false });
    const before = searches.length;
    await page.waitForTimeout(300);
    assert.equal(searches.length, before, "Changing the filter draft does not query products");
    await filter.getByRole("button", { name: "Xem kết quả", exact: true }).click();
    await page.waitForURL("**/main/product?**");
    await page.getByRole("heading", { name: /^Kết quả tìm kiếm: cpu/ }).waitFor();
    const expected = { q: "cpu", category_id: "COMP", subcategory_id: "CPU", brand: "Intel", min_price: "1000000", max_price: "5000000", stock_status: "in-stock", sort: "price-asc" };
    for (const [key, value] of Object.entries(expected)) assert.equal(new URL(page.url()).searchParams.get(key), value);
    await page.waitForFunction(() => !!document.querySelector('[aria-label="Catalog products"]'));
    assert.ok(searches.some(params => Object.entries(expected).every(([key, value]) => params.get(key) === value)));
    await page.reload();
    await page.getByRole("heading", { name: /^Kết quả tìm kiếm: cpu/ }).waitFor();
    await openSearch(); await openFilters();
    assert.equal(await filter.getByLabel("Giá từ", { exact: true }).inputValue(), "1000000");
    assert.equal(await filter.getByRole("combobox", { name: "Tình trạng hàng", exact: true }).inputValue(), "in-stock");
    await header.getByRole("button", { name: /^Bộ lọc/ }).click();
    await input.fill("cpu test");
    const suggestions = page.getByRole("region", { name: "Sản phẩm đề xuất", exact: true });
    await suggestions.getByText(product.name, { exact: true }).waitFor();
    assert.ok(searches.some(params => params.get("q") === "cpu test" && params.get("min_price") === "1000000" && params.get("brand") === "Intel" && params.get("stock_status") === "in-stock"));
    mode = "empty"; await input.fill("Samsung");
    await suggestions.getByText(/Không tìm thấy sản phẩm nào khớp/).waitFor();
    assert.equal(await suggestions.getByRole("option").count(), 0, "No fake fallback products when API has no matches");
    mode = "error"; await input.fill("API error");
    await suggestions.getByRole("alert").getByText("Không tải được tìm kiếm thử nghiệm.", { exact: true }).waitFor();
    mode = "ready";
    await input.press("Escape");
    await openSearch(); await openFilters();
    await filter.getByRole("button", { name: "Xóa bộ lọc", exact: true }).click();
    assert.equal(await filter.getByLabel("Giá từ", { exact: true }).inputValue(), "");
    await filter.getByRole("combobox", { name: "Thương hiệu", exact: true }).selectOption("AMD");
    await header.getByRole("button", { name: "Xóa nội dung tìm kiếm", exact: true }).click();
    await filter.getByRole("button", { name: "Xem kết quả", exact: true }).click();
    await page.waitForURL(url => url.pathname === "/main/product" && url.searchParams.get("brand") === "AMD" && !url.searchParams.has("q"));
    await page.setViewportSize({ width: 390, height: 844 });
    await openSearch(); await openFilters();
    await filter.getByLabel("Giá từ", { exact: true }).fill("1000000");
    await filter.getByRole("combobox", { name: "Tình trạng hàng", exact: true }).selectOption("out-of-stock");
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: path.join(os.tmpdir(), "phub-search-filters-mobile.png"), fullPage: false });
    await filter.getByRole("button", { name: "Xem kết quả", exact: true }).click();
    await page.waitForURL(url => url.searchParams.get("stock_status") === "out-of-stock" && url.searchParams.get("brand") === "AMD");
    await page.getByRole("button", { name: "Xóa bộ lọc Hết hàng", exact: true }).click();
    await page.waitForURL(url => !url.searchParams.has("stock_status") && url.searchParams.get("brand") === "AMD");
    await header.getByRole("button", { name: "Mở danh mục", exact: true }).click();
    const drawer = page.getByRole("dialog", { name: "Danh mục sản phẩm", exact: true });
    await drawer.getByRole("button", { name: "Vi xử lý", exact: true }).click();
    await page.waitForURL(url => url.searchParams.get("subcategory_id") === "CPU" && !url.searchParams.has("brand"));
    await openSearch();
    assert.equal(await input.inputValue(), "", "Persistent search resets from the current route");
    assert.deepEqual(errors, []); assert.deepEqual(writes, []);
    console.log("PASS: combined filters, price validation, URL/result requests, refresh persistence, filtered suggestions, empty/error states, filter-only search and mobile chips/layout");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
